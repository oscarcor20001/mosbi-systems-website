let currentLanguage = 'en';

function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) lang = 'en';
  currentLanguage = lang;
  localStorage.setItem('mosbi_lang', lang);
  document.documentElement.lang = lang;

  // Update UI code badge
  const codeEl = document.getElementById('currentLangCode');
  if (codeEl) codeEl.textContent = lang.toUpperCase();

  // Update active option in menu
  document.querySelectorAll('.lang-option').forEach(opt => {
    if (opt.getAttribute('data-lang') === lang) {
      opt.classList.add('active');
    } else {
      opt.classList.remove('active');
    }
  });

  // Translate all marked DOM elements
  const dict = TRANSLATIONS[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (dict[key].includes('<') && dict[key].includes('>')) {
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // Translate placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Re-render active machine scanner data in new language
  if (typeof loadMachine === 'function') {
    loadMachine(currentActiveMachine || 'goulds', typeof currentActiveSlot !== 'undefined' ? currentActiveSlot : 0);
  }

  // Re-render active industry data in new language
  if (typeof loadIndustry === 'function') {
    loadIndustry(currentActiveIndustry || 'manufacturing');
  }

  // Update contact select dropdown options if available
  const deptSelect = document.getElementById('departmentSelect');
  if (deptSelect && deptSelect.options.length >= 3) {
    deptSelect.options[0].text = dict['contact.opt_sales'] || deptSelect.options[0].text;
    deptSelect.options[1].text = dict['contact.opt_info'] || deptSelect.options[1].text;
    deptSelect.options[2].text = dict['contact.opt_support'] || deptSelect.options[2].text;
  }

  // Notify listeners of language change
  try { window.dispatchEvent(new CustomEvent('mosbi_lang_change', { detail: { lang: lang } })); } catch (e) {}
}

function initLanguageSelector() {
  const dropdown = document.getElementById('langSelector');
  const btn = document.getElementById('langBtn');
  const options = document.querySelectorAll('.lang-option');

  if (!dropdown || !btn) return;

  btn.addEventListener('click', (e) => {
    e.stopPropagation();
    const isOpen = dropdown.classList.toggle('open');
    btn.setAttribute('aria-expanded', isOpen);
  });

  options.forEach(opt => {
    opt.addEventListener('click', (e) => {
      e.stopPropagation();
      const lang = opt.getAttribute('data-lang');
      setLanguage(lang);
      dropdown.classList.remove('open');
      btn.setAttribute('aria-expanded', 'false');
      
      const langNames = { en: 'English', es: 'Español', fr: 'Français' };
      showToast(`Language: ${langNames[lang] || lang.toUpperCase()}`);
    });
  });

  // Close dropdown on outside click
  document.addEventListener('click', (e) => {
    if (!dropdown.contains(e.target)) {
      dropdown.classList.remove('open');
      btn.setAttribute('aria-expanded', 'false');
    }
  });

  // Close on Escape
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && dropdown.classList.contains('open')) {
      dropdown.classList.remove('open');
      btn.setAttribute('aria-expanded', 'false');
      btn.focus();
    }
  });

  // Load saved language preference or browser default
  const savedLang = localStorage.getItem('mosbi_lang');
  if (savedLang && TRANSLATIONS[savedLang]) {
    setLanguage(savedLang);
  } else {
    const browserLang = (navigator.language || navigator.userLanguage || 'en').substring(0, 2).toLowerCase();
    if (TRANSLATIONS[browserLang]) {
      setLanguage(browserLang);
    } else {
      setLanguage('en');
    }
  }
}